#!/usr/bin/env python3
"""NanoGPT plots with MPI Hierarchical rate8 explicitly enabled (distinct runner filename).

INCLUDED: baseline; Ring/RD uncompressed; Ring/RD ZFP naive and online at all
recorded rates; Hierarchical MPI rate8 and Hierarchical NCCL/RCCL variants.
EXCLUDED: Hierarchical MPI rates other than8, Direct, k-ring, diagnostics, other families.

This is a single replacement file. It uses existing thesisplots.cli/data/render
modules; no shared module edits required. Layouts, colors, units, source rules,
side-by-side comparisons, one shared legend and output tree are preserved.

Default views: vertical time/hook bars, time/hook scaling lines, paired
horizontal train-time/exposed-tail comparisons for each fixed GPU count. There
are NO horizontal time/hook bars unless --horizontal-bars is explicitly given.

Run from your supercomputer project folder:

  python3 thesis_plotting/plot_all_nanogpt_mpi_hier8.py \
      experiments_frontier experiments_frontier_rccl \
      --system frontier --mode strong --global-batch 768 \
      --output-root "uic thesis plots"

  python3 thesis_plotting/plot_all_nanogpt_mpi_hier8.py \
      experiments_polaris experiments_polaris_nccl \
      --system polaris --mode strong --global-batch 768 \
      --combine-simulated --output-root "uic thesis plots"

--combine-simulated copies the behavior of plot_gpt_backend_focus.py: it admits
synthetic records with complete numeric epoch coverage, aligns only model
suffix _simulated and dataset prefix simulated_ in memory, and preserves
original labels, source kind and completion evidence in normalized source data.
Source kind remains identified by estimate markers and provenance; the automatic figure title uses the ordinary workload description. No timing is changed or synthetic
value relabeled as an executed measurement. Explicit ESTIMATED source blocks
are accepted without a separate flag and retain estimate markers/provenance. Ordinary executed records need no
simulation/prediction flag. Without the option, original source groups remain
separate. This is a provenance distinction, not a judgment about data validity.

All usual batch options remain: --metrics time hook tail tail_pct; --layouts
bars lines hbar; --scopes all fixed; --normalizations; --comparisons-only;
--gpus; --backend; --rates; --unit; --ymax; --width; --formats; --config;
--include-partial; --include-predicted; --dry-run; --max-plots; --skip-existing.
--no-tail-context selects legacy tail-only layouts. --no-horizontal-bars is the
default. --system may name one or both machines; omitted means both.
Use a fresh output root when replacing earlier outputs: this runner will not
delete obsolete horizontal figures generated by older scripts.
"""
from pathlib import Path
import argparse,copy,json,html,sys,hashlib,collections,inspect,re
from collections import Counter
from thesisplots.cli import parser,parse
from thesisplots.data import load_inputs,export_runs
from thesisplots.render import create,select,workload,NoData
from thesisplots.style import family

FAMILIES=('baseline','ring','recursive doubling','hierarchical')



def mark_explicit_estimates(runs):
    """Recognize parseable ESTIMATED blocks without an extra command flag.

    The estimate label is per run, never inferred from a whole mixed log file.
    Original timing values and completion fields are not rewritten.
    """
    sources={};out=[]
    for original in runs:
        r=copy.deepcopy(original)
        source=Path(r['source'])
        if source.is_file() and source.suffix.lower() in ('.out','.log','.txt'):
            if str(source) not in sources:sources[str(source)]=source.read_text(errors='replace').splitlines()
            lines=sources[str(source)];start=max(0,int(r.get('source_line',1))-1);stop=len(lines)
            for i in range(start+1,len(lines)):
                if re.match(r'^=== Starting(?: training)?:',lines[i]):stop=i;break
            block='\n'.join(lines[start:stop])
            if re.search(r'^=== (?:Starting|Finished)(?: training)?:.*? at ESTIMATED\b',block,re.M):
                r['result_kind']='predicted'
                r['comparison_source_kind']='estimated'
                r.setdefault('warnings',[]).append('ESTIMATED source block, not an executed measurement; admitted without an extra flag. Original labels/timings retained.')
        out.append(r)
    return out


def prepare_runs(runs,allruns,combine):
    if not combine:return runs
    included={r['id']:r for r in runs}
    for r in allruns:
        simulated='simulated' in (r['model']+' '+r['dataset']).lower()
        covered={e['epoch'] for e in r['epochs_data'] if e.get('finished') and e.get('train_s') is not None}
        if simulated and not r.get('quarantined') and r.get('train_summary_s') is not None and covered==set(range(1,r['epochs']+1)):
            included[r['id']]=r
    out=[]
    for original in included.values():
        r=copy.deepcopy(original)
        simulated='simulated' in (r['model']+' '+r['dataset']).lower()
        r['comparison_source_kind']='simulated' if simulated else original.get('comparison_source_kind','logged')
        r['original_model']=r['model'];r['original_dataset']=r['dataset']
        r['model']=r['model'].removesuffix('_simulated')
        r['dataset']=r['dataset'].removeprefix('simulated_')
        if simulated:
            r['result_kind']='predicted'
            r.setdefault('warnings',[]).append('SIMULATED source explicitly included in mixed comparison; original model='+r['original_model']+'; original dataset='+r['original_dataset']+'; timings unchanged.')
        out.append(r)
    return out



def include_predictions_compat(runs,allruns,enabled):
    """Read explicit prediction provenance even with older shared loaders."""
    cache={};predictions={}
    for original in allruns:
        marked=original.get('result_kind')=='predicted'
        source=Path(original['source'])
        if source.is_file() and source.suffix.lower() in ('.out','.log','.txt'):
            key=str(source)
            if key not in cache:cache[key]=source.read_text(errors='replace').splitlines()
            lines=cache[key];start=max(0,int(original.get('source_line',1))-1);stop=len(lines)
            for i in range(start+1,len(lines)):
                if re.match(r'^=== Starting(?: training)?:',lines[i]):stop=i;break
            block='\n'.join(lines[start:stop])
            marked=marked or bool(re.search(r'^=== (?:Starting|Finished)(?: training)?:.*?(?:status=PREDICTED| at PREDICTED\b)',block,re.M))
        if not marked:continue
        r=copy.deepcopy(original);r['result_kind']='predicted';r['comparison_source_kind']='predicted'
        r.setdefault('warnings',[]).append('Explicit prediction admitted by standalone runner compatibility layer; no execution status or timing changed.')
        predictions[r['id']]=r
    included={r['id']:r for r in runs if r['id'] not in predictions}
    if enabled:
        for key,r in predictions.items():
            covered={e['epoch'] for e in r['epochs_data'] if e.get('finished') and e.get('train_s') is not None}
            if not r.get('quarantined') and r.get('train_summary_s') is not None and covered==set(range(1,r['epochs']+1)):
                included[key]=r
    return list(included.values())


def run_system(system,argv=None):
    p=parser(description=f'Generate the full {system.title()} thesis plotting tree. Inputs may be code_oct26, system roots, raw files, or exported CSV.')
    p.add_argument('--output-root',type=Path,default=Path('plots_thesis_nanogpt'))
    p.add_argument('--scopes',nargs='+',choices=['all','fixed'],default=['all','fixed'],help='all: GPU sweeps; fixed: each GPU count, plus varying-batch plots at fixed GPU count')
    p.add_argument('--metrics',nargs='+',choices=['time','hook','tail','tail_pct'],default=['time','hook','tail'])
    p.add_argument('--layouts',nargs='+',choices=['bars','lines','hbar'],default=['bars','lines','hbar'])
    p.add_argument('--normalizations',nargs='+',choices=['absolute','baseline','speedup','efficiency'],default=['absolute'])
    p.add_argument('--comparisons',action=argparse.BooleanOptionalAction,default=True,help='Also generate matching MPI/native-backend comparison panels')
    p.add_argument('--comparisons-only',action='store_true',help='Regenerate backend comparisons only, preserving other indexed figures')
    p.add_argument('--combine-simulated',action='store_true',help='Explicitly combine compatible logged and simulated records, preserving original metadata and timings')
    p.add_argument('--horizontal-bars',action=argparse.BooleanOptionalAction,default=False,help='Also create horizontal time/hook bars; paired tail bars remain horizontal regardless')
    if '--include-predicted' not in p._option_string_actions:p.add_argument('--include-predicted',action='store_true')
    p.add_argument('--max-plots',type=int,help='Optional preview limit; manifest reports truncation')
    p.add_argument('--dry-run',action='store_true',help='Write planned jobs and audit only')
    p.add_argument('--skip-existing',action='store_true',help='Skip a figure when its JSON sidecar exists')
    args=parse(p,argv);args.system=[system]
    options=dict(system=args.assume_system,mode=args.mode,include_partial=args.include_partial)
    if 'include_predicted' in inspect.signature(load_inputs).parameters:options['include_predicted']=args.include_predicted
    runs,issues,allruns=load_inputs(args.inputs,**options)
    runs=include_predictions_compat(runs,allruns,args.include_predicted)
    runs=mark_explicit_estimates(runs)
    runs=prepare_runs(runs,allruns,args.combine_simulated)
    # Requested MPI hierarchy is rate8; native-backend hierarchy stays unchanged.
    runs=[r for r in runs if not (r['backend']=='mpi' and family(r['method'])=='Hierarchical' and str(r.get('zfp_rate'))!='8')]
    if args.lr is not None:runs=[r for r in runs if r['lr']==args.lr]
    runs=select(runs,args);runs=[r for r in runs if r['mode'] in ('strong','weak')]
    hierarchy_gpus=sorted({r['ranks'] for r in runs if r['backend']=='mpi' and family(r['method'])=='Hierarchical' and str(r.get('zfp_rate'))=='8'})
    print(f'{system}: hierarchical MPI rate8 selected at GPU counts: {hierarchy_gpus}',flush=True)
    base=args.output_root/system;base.mkdir(parents=True,exist_ok=True);export_runs([r for r in allruns if r['system']==system],base/'parsed_runs.csv');(base/'input_issues.json').write_text(json.dumps(issues,indent=2))
    export_runs(runs,base/'selected_runs.csv')
    groups={}
    for r in runs:
        key=(r['family'],r['mode'],r['backend'])+workload(r,'ranks')+((r['lr'] if r['mode']=='strong' else None),)
        groups.setdefault(key,[]).append(r)
    jobs=[]
    def add(rr,scope,x,tag,layouts):
        if args.comparisons_only and len({z['backend'] for z in rr})<2:return
        r=rr[0]
        for metric in args.metrics:
            for layout in layouts:
                if metric in ('time','hook') and layout=='hbar' and not args.horizontal_bars:continue
                # Default tails compare two bars at a single configuration.
                if metric=='tail' and args.tail_context and layout!='hbar':continue
                if layout=='hbar' and len({(z['effective_batch'] if x=='global_batch' else z[x]) for z in rr})>1:continue
                for norm in args.normalizations:
                    if norm!='absolute' and metric!='time':continue
                    if norm in ('speedup','efficiency') and (layout!='lines' or r['mode']!='strong' or x!='ranks' or scope=='fixed'):continue
                    category='normal' if metric=='time' and layout!='lines' else ('lines' if metric=='time' else 'hooks' if metric=='hook' else 'tails')
                    backend_folder='backend_comparison' if len({z['backend'] for z in rr})>1 else r['backend']
                    folder=base/r['family']/(r['mode']+'Scaling')/backend_folder/category
                    unit=('epoch' if r['mode']=='strong' else 'iter') if args.unit=='auto' else args.unit
                    stem=folder/(tag+'_'+scope+'_'+layout+'_'+metric+'_'+(unit if metric!='time' else norm))
                    jobs.append((rr,dict(scope=scope,x=x,metric=metric,layout=layout,normalize=norm,stem=str(stem))))
    for key,rr in sorted(groups.items(),key=lambda kv:str(kv[0])):
        r=rr[0];tag=('GB'+str(r['effective_batch'])) if r['mode']=='strong' else ('LB'+str(r['batch_per_rank']))
        if 'all' in args.scopes:add(rr,'all','ranks',tag,[l for l in args.layouts if l!='hbar'])
        if 'fixed' in args.scopes:
            for gpu in sorted({z['ranks'] for z in rr}):add([z for z in rr if z['ranks']==gpu],'fixed','ranks',tag+'_gpu'+str(gpu),[l for l in args.layouts if l!='lines'])
    if args.comparisons:
        compare_groups={}
        for r in runs:
            key=workload(r,'ranks')+((r['lr'] if r['mode']=='strong' else None),)
            compare_groups.setdefault(key,[]).append(r)
        for key,rr in sorted(compare_groups.items(),key=lambda kv:str(kv[0])):
            if len({r['backend'] for r in rr})<2:continue
            r=rr[0];tag=('GB'+str(r['effective_batch'])) if r['mode']=='strong' else ('LB'+str(r['batch_per_rank']))
            if 'all' in args.scopes:add(rr,'all','ranks',tag,[l for l in args.layouts if l!='hbar'])
            if 'fixed' in args.scopes:
                for gpu in sorted({z['ranks'] for z in rr}):
                    fixed=[z for z in rr if z['ranks']==gpu]
                    if len({z['backend'] for z in fixed})>1:add(fixed,'fixed','ranks',tag+'_gpu'+str(gpu),[l for l in args.layouts if l!='lines'])
    # At fixed GPU count, compare different batch sizes without mixing models.
    if 'fixed' in args.scopes:
        batchgroups={}
        for r in runs:
            key=(r['system'],r['family'],r['model'],r['dataset'],r['image_size'],r['mode'],r['backend'],r['ranks'],r.get('block_size'))
            batchgroups.setdefault(key,[]).append(r)
        for key,rr in sorted(batchgroups.items(),key=lambda kv:str(kv[0])):
            x='global_batch' if rr[0]['mode']=='strong' else 'batch_per_rank'
            if len({r['effective_batch'] if x=='global_batch' else r[x] for r in rr})>1:add(rr,'fixed',x,'gpu'+str(rr[0]['ranks'])+'_vary_batch',[l for l in args.layouts if l!='hbar'])
    # Disambiguate models/datasets/block sizes sharing short batch tags.
    counts=collections.Counter(j['stem'] for rr,j in jobs)
    for rr,j in jobs:
        if counts[j['stem']]>1:
            configs=sorted({str((r['model'],r['dataset'],r['image_size'],r.get('block_size'),r['lr'] if r['mode']=='strong' else None)) for r in rr})
            suffix=hashlib.sha256(repr(configs).encode()).hexdigest()[:8]
            j['stem']+='__cfg'+suffix
    truncated=args.max_plots is not None and len(jobs)>args.max_plots
    if args.max_plots is not None:jobs=jobs[:args.max_plots]
    report=dict(system=system,inputs=[str(Path(x).resolve()) for x in args.inputs],completed_runs=len(runs),all_runs=len([r for r in allruns if r['system']==system]),planned=len(jobs),truncated=truncated,dry_run=args.dry_run,plots=[])
    for i,(rr,j) in enumerate(jobs):
        item=j.copy();stem=Path(j['stem'])
        if args.dry_run:item['status']='planned'
        elif args.skip_existing and stem.with_suffix('.json').exists():item['status']='existing'
        else:
            aa=copy.copy(args)
            for k in ['x','metric','layout','normalize']:setattr(aa,k,j[k])
            if len({z['backend'] for z in rr})>1:aa.columns=2;aa.width=max(18,aa.width)
            simulation_gpus=sorted({r['ranks'] for r in rr if r.get('comparison_source_kind')=='simulated' or 'simulated' in (r['model']+' '+r['dataset']).lower()})
            if simulation_gpus:
                aa.title=args.title  # Use the ordinary workload title; source-kind markers/provenance remain.
            try:
                result=create(rr,aa,stem);item.update(status='written',points=len(result['points']),omitted=len(result['omitted']))
            except NoData as exc:item.update(status='no_metric',reason=str(exc))
            except (ValueError,KeyError) as exc:item.update(status='error',reason=str(exc))
        report['plots'].append(item)
        if (i+1)%20==0:print(f'{system}: {i+1}/{len(jobs)} figures processed',flush=True)
    if not runs:report['notice']='No matching runs; verify input path and system names. No fabricated figures generated.'
    if args.comparisons_only and (base/'manifest.json').exists():
        previous=json.loads((base/'manifest.json').read_text());updated={j['stem'] for j in report['plots']}
        report['plots']=[j for j in previous['plots'] if j['stem'] not in updated]+report['plots']
    (base/'manifest.json').write_text(json.dumps(report,indent=2))
    links=[]
    for j in report['plots']:
        if j['status'] in ('written','existing'):
            path=Path(j['stem']).relative_to(base).as_posix()+'.html';links.append(f'<li><a href="{html.escape(path)}">{html.escape(path[:-5])}</a></li>')
    (base/'index.html').write_text(f'<!doctype html><html lang="en"><meta charset="utf-8"><title>{system.title()} thesis plots</title><style>body{{font:18px/1.5 Arial;max-width:70rem;margin:2rem auto;padding:1rem;background:white;color:#111}}a{{color:#0645ad}}</style><h1>{system.title()} thesis plots</h1><p>{len(runs)} completed/selected runs. See manifest.json and input_issues.json for unavailable metrics, incomplete jobs and provenance. These figure packages do not certify the final thesis document.</p><ul>'+''.join(links)+'</ul></html>')
    counts=Counter(j['status'] for j in report['plots']);print(f'{system}: {dict(counts)}; index: {base/"index.html"}')
    report['nanogpt_preset']=dict(excluded=['Direct','k-ring','DDP diagnostics','MPI Hierarchical rates other than8'],combine_simulated=args.combine_simulated,horizontal_time_hook_bars=args.horizontal_bars)
    (base/'manifest.json').write_text(json.dumps(report,indent=2))
    return report


def main(argv=None):
    argv=list(sys.argv[1:] if argv is None else argv)
    # Remove only wrapper-owned options; everything else goes to the unchanged
    # batch parser, including positional folders/files/CSV and all shared flags.
    p=argparse.ArgumentParser(add_help=False)
    p.add_argument('--system',nargs='+',choices=['frontier','polaris'])
    p.add_argument('--output-root',type=Path,default=Path('plots_thesis_nanogpt'))
    own,forward=p.parse_known_args(argv)
    systems=own.system or ['frontier','polaris']
    if '--help' in argv or '-h' in argv:
        print(__doc__)
        print('\nFull shared batch options follow:\n')
        run_system(systems[0],forward+['--help'])
        return
    # Last-occurring explicit flags override conflicting profile/default flags.
    # The existing selector applies every restriction before scheduling figures.
    forced=['--model','gpt','--families',*FAMILIES,
            '--direct','omit','--no-diagnostics','--output-root',str(own.output_root)]
    reports=[]
    for system in systems:
        reports.append(run_system(system,forward+forced))
    own.output_root.mkdir(parents=True,exist_ok=True)
    preset=dict(model_family='gpt',included_families=list(FAMILIES),
                excluded=['Direct','k-ring','DDP diagnostics','MPI Hierarchical rates other than8','Other'],
                systems=systems,argv=argv,
                manifests=[str(own.output_root/s/'manifest.json') for s in systems])
    (own.output_root/'nanogpt_preset.json').write_text(json.dumps(preset,indent=2))
    links=''.join('<li><a href="'+s+'/index.html">'+s.title()+'</a></li>' for s in systems)
    (own.output_root/'index.html').write_text('<!doctype html><html lang="en"><meta charset="utf-8"><title>NanoGPT selected-family plots</title><h1>NanoGPT plots</h1><p>Baseline, Ring, recursive doubling, ZFP naive/online, MPI Hierarchical rate8 and native-backend Hierarchical. Original plotting styles and metrics.</p><ul>'+links+'</ul></html>')
    return reports


if __name__=='__main__':main()
